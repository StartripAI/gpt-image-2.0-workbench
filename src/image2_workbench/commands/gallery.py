"""`i2w gallery build` — compile the bilingual paste-ready gallery from templates.

The gallery is the L3 (no-runtime) surface of the workbench: pre-rendered
markdown that anyone can copy into web ChatGPT. This command walks the
template index, renders every template with its canonical demo vars, and
writes one ``<domain>.md`` file per V1 domain. The shared ``index.md``
under ``docs/gallery/`` is owned elsewhere and is *not* touched here.
"""
from __future__ import annotations

from pathlib import Path
from typing import Annotated

import typer
from rich.console import Console

from ..catalog import index as catalog_index
from ..compiler.loader import load_template, load_vars
from ..compiler.renderer import render_both

gallery_app = typer.Typer(
    no_args_is_help=True,
    help="Build markdown gallery from templates.",
)


