"""`i2w gallery build` / `i2w gallery readme` — paste-ready gallery surfaces.

The gallery is the L3 (no-runtime) surface of the workbench: pre-rendered
markdown that anyone can copy into web ChatGPT. ``build`` walks the
template index, renders every template with its canonical demo vars, and
writes one ``<domain>.md`` file per V1 domain. ``readme`` is the L0
no-friction surface: it produces a compact inline-atlas section for the
GitHub homepage README, optionally injecting it between marker comments
in a target file (round-trip-safe — re-injecting after edits doesn't
drift). The shared ``index.md`` under ``docs/gallery/`` is owned
elsewhere and is *not* touched here.
"""
