def _domain_emoji(domain: str) -> str:
    """Return the registered glyph for ``domain`` (or ``📁`` if unknown)."""
    return _DOMAIN_EMOJI.get(domain, "📁")


def _excerpt(spec_obj: object, max_chars: int = 60) -> str:
    """Return a one-line, Jinja-stripped, length-capped use-case teaser.

    Resolution: ``spec.description`` (if non-empty) > ``spec.spec.subject``.
    Strips Jinja ``{{var}}`` placeholders to ``…``, collapses whitespace,
    and truncates with a trailing ellipsis when over ``max_chars``.

    Accepts a ``TemplateSpec`` (preferred) but is duck-typed so tests can
    pass simple namespace objects.
    """
    description = getattr(spec_obj, "description", None) or ""
    subject = ""
    inner_spec = getattr(spec_obj, "spec", None)
    if inner_spec is not None:
        subject = getattr(inner_spec, "subject", "") or ""
    raw = (description or subject or "").strip()
    raw = _JINJA_PLACEHOLDER_RE.sub("…", raw)
    raw = _WHITESPACE_RE.sub(" ", raw).strip()
    if len(raw) > max_chars:
        raw = raw[: max_chars - 1].rstrip() + "…"
    return raw


def _generate_section(
    *,
    lang: str,
    max_excerpt_chars: int,
) -> str:
    """Build the compact inline-atlas section (markers included)."""
    entries = catalog_index.list_templates()
    by_domain: dict[str, list[Path]] = {}
    for entry in entries:
        by_domain.setdefault(entry.domain, []).append(Path(entry.path))

    domain_count = len(by_domain)
    template_count = sum(len(paths) for paths in by_domain.values())

    if lang == "zh-CN":
        header = f"## 模板图册 — {domain_count} 个领域，{template_count} 个模板"
        intro = (
            f"当前扩展图册覆盖 {domain_count} 个领域；每个领域都有一页可复制的双语 prompt "
            "gallery，也能从同一份 YAML 模板走 CLI / Skill / API。"
        )
        cols = ("领域", "模板数", "适合做什么", "代表模板", "入口")
        gallery_label = "图册"
        templates_label = "模板"
        docs_label = "继续看："
        docs_links = (
            '<a href="docs/getting-started.zh.md">快速上手</a> · '
            '<a href="docs/chatgpt-web-mode.md">网页 ChatGPT 用法</a> · '
            '<a href="docs/cost-modeling.md">成本模型</a>'
        )
    else:
        header = f"## Atlas — {domain_count} domains, {template_count} templates"
        intro = (
            f"The current extended atlas covers {domain_count} domains. Each domain has a "
            "copy-ready bilingual gallery page, and the same YAML templates drive "
            "CLI, Skill, and API workflows."
        )
        cols = ("Domain", "Templates", "Good for", "Representative templates", "Open")
        gallery_label = "Gallery"
        templates_label = "Templates"
        docs_label = "Read next:"
        docs_links = (
            '<a href="docs/getting-started.en.md">Getting started</a> · '
            '<a href="docs/chatgpt-web-mode.md">Web ChatGPT mode</a> · '
            '<a href="docs/cost-modeling.md">Cost modeling</a>'
        )

    parts: list[str] = [
        README_BEGIN_FULL,
        "",
        '<a id="atlas--30-domains-80-templates"></a>',
        header,
        "",
        intro,
        "",
    ]
    parts.append(f"| {cols[0]} | {cols[1]} | {cols[2]} | {cols[3]} | {cols[4]} |")
    parts.append("|---|---:|---|---|---|")

    sorted_domains = sorted(by_domain.items())
    for dom, paths in sorted_domains:
        sorted_paths = sorted(paths, key=lambda p: p.stem)
        specs = [load_template(path) for path in sorted_paths[:2]]
        excerpt_source = specs[0] if specs else load_template(sorted_paths[0])
        excerpt = _excerpt(excerpt_source, max_chars=max_excerpt_chars)
        excerpt = excerpt.replace("|", "\\|")
        reps = " · ".join(f"`{spec.id}`" for spec in specs)
        domain_label = f"{_domain_emoji(dom)} `{dom}`"
        links = (
            f'<a href="docs/gallery/{dom}.md">{gallery_label}</a> · '
            f'<a href="templates/{dom}/">{templates_label}</a>'
        )
        parts.append(
            f"| {domain_label} | {len(paths)} | {excerpt} | {reps} | {links} |"
        )
    parts.append("")
    parts.append(f"<p><strong>{docs_label}</strong> {docs_links}</p>")
    parts.append("")
    parts.append(README_END_MARKER)

    return "\n".join(parts)


def _replace_section(existing: str, section: str) -> str:
    """Replace the marker-delimited gallery section in ``existing`` with ``section``.

    Locates ``<!-- BEGIN GALLERY`` (just the prefix; tolerates the
    auto-generated suffix) and ``<!-- END GALLERY -->`` markers and
    swaps everything between them inclusive. Raises a workbench
    ``validation_error`` when either marker is missing.
    """
    begin_idx = existing.find(README_BEGIN_PREFIX)
    if begin_idx == -1:
        raise validation_error(
            "gallery_marker_missing",
            f"BEGIN GALLERY marker not found; expected line containing "
            f"{README_BEGIN_PREFIX!r}",
        )
    end_idx = existing.find(README_END_MARKER, begin_idx)
    if end_idx == -1:
        raise validation_error(
            "gallery_marker_missing",
            f"END GALLERY marker not found after BEGIN; expected "
            f"{README_END_MARKER!r}",
        )
    end_idx += len(README_END_MARKER)
    return existing[:begin_idx] + section + existing[end_idx:]


def _atomic_write(target: Path, content: str) -> None:
    """Write ``content`` to ``target`` atomically via a sibling tmp file."""
    tmp = target.with_suffix(target.suffix + ".tmp")
    tmp.write_text(content, encoding="utf-8")
    os.replace(tmp, target)


@gallery_app.command("readme")
def readme(
    lang: Annotated[str, typer.Option("--lang", help="zh-CN | en")] = "en",
    out: Annotated[
        Path | None,
        typer.Option("--out", help="Write the section to this file"),
    ] = None,
    inject: Annotated[
        Path | None,
        typer.Option(
            "--inject",
            help=(
                "Replace content between <!-- BEGIN GALLERY --> and "
                "<!-- END GALLERY --> markers in this file"
            ),
        ),
    ] = None,
    check: Annotated[
        Path | None,
        typer.Option(
            "--check",
            help="Verify the file's gallery section is up to date; exit 4 if drift",
        ),
    ] = None,
    max_excerpt_chars: Annotated[
        int,
        typer.Option("--max-excerpt-chars", help="Max chars of prompt excerpt per card"),
    ] = 90,
) -> None:
    """Generate the inline-atlas section for README.{md,zh.md}."""
    console = Console()

    def _run() -> None:
        modes = [m for m in (out, inject, check) if m is not None]
        if len(modes) != 1:
            raise validation_error(
                "gallery_readme_mode",
                "exactly one of --out, --inject, --check is required",
                context={
                    "out": str(out) if out is not None else None,
                    "inject": str(inject) if inject is not None else None,
                    "check": str(check) if check is not None else None,
                },
            )

        if lang not in ("zh-CN", "en"):
            raise validation_error(
                "gallery_readme_lang",
                f"unsupported --lang {lang!r}; expected 'en' or 'zh-CN'",
                context={"lang": lang},
            )

        section = _generate_section(lang=lang, max_excerpt_chars=max_excerpt_chars)

        if out is not None:
            out.parent.mkdir(parents=True, exist_ok=True)
            _atomic_write(out, section + "\n")
            console.print(
                f"wrote gallery section ({len(section)} chars) to {out}",
                markup=False,
            )
            return

        if inject is not None:
            if not inject.is_file():
                raise validation_error(
                    "gallery_readme_target_missing",
                    f"target file not found: {inject}",
                    context={"target": str(inject)},
                )
            existing = inject.read_text(encoding="utf-8")
            updated = _replace_section(existing, section)
            _atomic_write(inject, updated)
            console.print(
                f"injected gallery section into {inject}",
                markup=False,
            )
            return

        if check is not None:
            if not check.is_file():
                raise validation_error(
                    "gallery_readme_target_missing",
                    f"target file not found: {check}",
                    context={"target": str(check)},
                )
            existing = check.read_text(encoding="utf-8")
            updated = _replace_section(existing, section)
            if existing != updated:
                raise validation_error(
                    "gallery_section_drift",
                    f"{check} gallery section is out of date; "
                    f"run `i2w gallery readme --inject {check}` to refresh",
                    context={"target": str(check)},
                )
            console.print(
                f"{check} gallery section is up to date",
                markup=False,
            )
            return

    raise SystemExit(cli_dispatch(_run))


