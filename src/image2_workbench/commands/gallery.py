# Marker comments for round-trip-safe injection. The BEGIN marker tolerates
# the appended auto-generated suffix so re-runs find the section even after
# the body changed.
README_BEGIN_PREFIX = "<!-- BEGIN GALLERY"
README_END_MARKER = "<!-- END GALLERY -->"
README_BEGIN_FULL = (
    "<!-- BEGIN GALLERY (auto-generated by `i2w gallery readme`; "
    "do not edit by hand) -->"
)

_JINJA_PLACEHOLDER_RE = re.compile(r"\{\{[^}]+\}\}")
_WHITESPACE_RE = re.compile(r"\s+")

